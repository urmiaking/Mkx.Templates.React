import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve, basename } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const clientRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const solutionRoot = resolve(clientRoot, '..', '..')
const serverRoot = join(solutionRoot, 'src', 'Server')
const projectDirectories = readdirSync(serverRoot, { withFileTypes: true }).filter((entry) => entry.isDirectory())
const serverProjects = projectDirectories.flatMap((entry) =>
  readdirSync(join(serverRoot, entry.name))
    .filter((name) => name.endsWith('.Server.csproj'))
    .map((name) => join(serverRoot, entry.name, name))
)

if (serverProjects.length !== 1) {
  throw new Error(`Expected exactly one ASP.NET Core Server project under ${serverRoot}; found ${serverProjects.length}.`)
}

const projectFile = serverProjects[0]
const projectName = basename(projectFile, '.csproj')
const generatedSpec = join(dirname(projectFile), 'obj', `${projectName}.json`)
const outputFile = join(clientRoot, 'src', 'shared', 'api', 'schema.generated.ts')
const check = process.argv.includes('--check')

// Generate the OpenAPI document from endpoint metadata, without starting the app or database.
const result = spawnSync('dotnet', [
  'build', projectFile, '-c', 'Release',
  '-p:OpenApiGenerateDocumentsOnBuild=true', '-v:q'
], {
  cwd: solutionRoot,
  encoding: 'utf8',
  env: { ...process.env, ASPNETCORE_ENVIRONMENT: 'Production', DOTNET_ENVIRONMENT: 'Production' }
})

if (result.error || result.status !== 0) {
  throw new Error(`Unable to generate the Server OpenAPI contract.\n${result.stdout ?? ''}\n${result.stderr ?? ''}\n${result.error ?? ''}`)
}

if (!existsSync(generatedSpec)) {
  throw new Error(`OpenAPI build completed but no specification exists at ${generatedSpec}.`)
}

const document = JSON.parse(readFileSync(generatedSpec, 'utf8'))
const generatedTypes = astToString(await openapiTS(document)).replace(/\r\n/g, '\n').trimEnd() + '\n'
const expected = '// Auto-generated by npm run api:generate. Do not edit manually.\n' + generatedTypes

if (check) {
  if (!existsSync(outputFile) || readFileSync(outputFile, 'utf8').replace(/\r\n/g, '\n') !== expected) {
    throw new Error('OpenAPI contract drift detected. Run npm run api:generate and commit src/shared/api/schema.generated.ts alongside your endpoint changes.')
  }
  console.log('OpenAPI contract matches committed TypeScript types.')
} else {
  writeFileSync(outputFile, expected, 'utf8')
  console.log(`Updated ${outputFile} from ${projectName} OpenAPI.`)
}
